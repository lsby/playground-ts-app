import type { 测试模型 } from '../../src/model/requirement'
import type { 已审阅的any } from '../../src/tools/types'
import type { 扫描维度项, 扫描选项项, 流程展示项, 需求维度项 } from './requirement-selector-renderer'
import { 文本匹配搜索词 } from './requirement-selector-terminal'

export type 统一维度选项 = {
  值: string
  标签: string
  说明?: string | undefined
  是通配: boolean
  匹配: (流程项: 流程展示项) => boolean
}

export type 级联维度项 = {
  唯一标识: string
  分类: '标签' | '需求'
  名称: string
  说明?: string | undefined
  原始选项们: 统一维度选项[]
}

export type 活跃维度展示项 = 级联维度项 & { 当前有效选项们: 统一维度选项[]; 当前选中下标: number }

export type 级联计算结果 = {
  保留标签维度列表: 扫描维度项[]
  保留需求维度列表: 需求维度项[]
  标签选项下标们: number[]
  需求选项下标们: number[]
  候选流程列表: 流程展示项[]
  活跃维度列表: 活跃维度展示项[]
}

export function 从模型列表提取级联元数据(模型列表: 测试模型<已审阅的any, 已审阅的any>[]): {
  全部维度列表: 级联维度项[]
  流程列表: 流程展示项[]
} {
  let 维度映射 = new Map<
    string,
    {
      选项映射: Map<string, { 值: string; 标签: string; 说明?: string | undefined; 是通配: boolean }>
      说明?: string | undefined
    }
  >()

  let 依赖名称集 = new Set<string>()
  let 需求映射 = new Map<string, { 名称: string; 描述: string; 验收点集: Set<unknown> }>()

  for (let 模型 of 模型列表) {
    for (let 依赖 of 模型.元数据.依赖条件们) {
      依赖名称集.add(String(依赖))
    }
    for (let 当前需求 of 模型.需求们) {
      if (!需求映射.has(当前需求.名称)) {
        需求映射.set(当前需求.名称, { 名称: 当前需求.名称, 描述: 当前需求.描述, 验收点集: new Set(当前需求.验收点们) })
      }
    }
    for (let 维度 of 模型.元数据.标签维度们 ?? []) {
      let 已有 = 维度映射.get(维度.名称)
      if (已有 === undefined) {
        let 选项映射 = new Map<string, { 值: string; 标签: string; 说明?: string | undefined; 是通配: boolean }>()
        for (let 选项 of 维度.选项们) {
          选项映射.set(选项.标签, { 值: 选项.值, 标签: 选项.标签, 说明: 选项.说明, 是通配: 选项.是通配 })
        }
        维度映射.set(维度.名称, { 选项映射, 说明: 维度.说明 })
      } else {
        for (let 选项 of 维度.选项们) {
          if (!已有.选项映射.has(选项.标签)) {
            已有.选项映射.set(选项.标签, { 值: 选项.值, 标签: 选项.标签, 说明: 选项.说明, 是通配: 选项.是通配 })
          }
        }
      }
    }
  }

  let 流程列表: 流程展示项[] = []
  for (let 模型 of 模型列表) {
    for (let 当前流程 of 模型.流程们) {
      let 覆盖描述 = 当前流程.覆盖验收点们.map((点) => 点.描述).join('、')
      let 标签字典 = 当前流程.标签字典 ?? {}
      let 流程验收点集 = new Set<unknown>(当前流程.覆盖验收点们)
      let 所属需求名称们 = [...需求映射.values()]
        .filter((项) => [...项.验收点集].some((点) => 流程验收点集.has(点)))
        .map((项) => 项.名称)

      let 依赖条件集 = new Set<string>()
      let 包含人工验收 = false
      for (let 验收点 of 当前流程.覆盖验收点们) {
        if (验收点.验收手段 === '人工') 包含人工验收 = true
        for (let 方案 of 验收点.依赖方案们) {
          for (let 条件 of 方案) {
            依赖条件集.add(String(条件))
          }
        }
      }

      流程列表.push({
        流程: 当前流程,
        流程名称: 当前流程.名称,
        标签字典,
        覆盖描述,
        所属需求名称们,
        依赖条件集,
        包含人工验收,
        所属模型: 模型,
      })
    }
  }

  let 全部维度列表: 级联维度项[] = []

  // 1. 业务标签维度
  for (let [名称, 元信息] of 维度映射.entries()) {
    let 原始选项们: 统一维度选项[] = [...元信息.选项映射.values()].map((选项) => ({
      值: 选项.值,
      标签: 选项.标签,
      说明: 选项.说明,
      是通配: 选项.是通配,
      匹配: (流程项: 流程展示项): boolean => {
        let 流程值 = 流程项.标签字典[名称]
        return 流程值 === 选项.值 || 流程值 === 选项.标签
      },
    }))
    全部维度列表.push({ 唯一标识: `标签:${名称}`, 分类: '标签', 名称, 说明: 元信息.说明, 原始选项们 })
  }

  // 2. 环境依赖维度
  for (let 依赖名 of 依赖名称集) {
    全部维度列表.push({
      唯一标识: `需求:${依赖名}`,
      分类: '需求',
      名称: 依赖名,
      说明: `环境依赖条件，决定流程是否依赖“${依赖名}”能力。`,
      原始选项们: [
        {
          值: '不限',
          标签: '不限',
          说明: `不限制“${依赖名}”依赖，展示所有相关流程。`,
          是通配: true,
          匹配: (): boolean => true,
        },
        {
          值: '是',
          标签: '是',
          说明: `仅展示需要“${依赖名}”依赖环境的流程。`,
          是通配: false,
          匹配: (流程项: 流程展示项): boolean => 流程项.依赖条件集.has(依赖名),
        },
        {
          值: '否',
          标签: '否',
          说明: `仅展示无需“${依赖名}”依赖环境的流程。`,
          是通配: false,
          匹配: (流程项: 流程展示项): boolean => !流程项.依赖条件集.has(依赖名),
        },
      ],
    })
  }

  return { 全部维度列表, 流程列表 }
}

function 流程匹配搜索词(流程项: 流程展示项, 搜索词: string): boolean {
  if (搜索词.trim() === '') return true
  let 标签文本 = Object.entries(流程项.标签字典)
    .map(([k, v]) => `${k}:${v}`)
    .join(' ')
  let 需求文本 = 流程项.所属需求名称们.join(' ')
  let 检索文本 = `${流程项.流程名称} ${标签文本} ${需求文本} ${流程项.覆盖描述}`
  return 文本匹配搜索词(检索文本, 搜索词)
}

function 判断流程是否匹配维度选择(流程项: 流程展示项, 维度: 级联维度项, 当前选中值: string | undefined): boolean {
  if (当前选中值 === undefined) return true
  let 选中选项 = 维度.原始选项们.find((项) => 项.值 === 当前选中值)
  if (选中选项 === undefined || 选中选项.是通配 === true) return true
  return 选中选项.匹配(流程项)
}

export function 执行级联计算(参数: {
  全部维度列表: 级联维度项[]
  全部流程列表: 流程展示项[]
  当前选择值映射: Map<string, string>
  搜索词: string
}): 级联计算结果 {
  let 过滤流程集合 = (排除的维度标识?: string): 流程展示项[] => {
    return 参数.全部流程列表.filter((流程项) => {
      if (流程匹配搜索词(流程项, 参数.搜索词) === false) return false
      for (let 维度 of 参数.全部维度列表) {
        if (维度.唯一标识 === 排除的维度标识) continue
        let 选中值 = 参数.当前选择值映射.get(维度.唯一标识)
        if (判断流程是否匹配维度选择(流程项, 维度, 选中值) === false) {
          return false
        }
      }
      return true
    })
  }

  let 活跃维度列表: 活跃维度展示项[] = []

  for (let 维度 of 参数.全部维度列表) {
    let 通配选项 = 维度.原始选项们.find((项) => 项.是通配 === true) ?? 维度.原始选项们[0]
    let 基准流程集合 = 过滤流程集合(维度.唯一标识)

    // 筛选出在当前基准流程集合中实际存在匹配流程的非通配选项
    let 有效非通配选项们 = 维度.原始选项们.filter((项) => {
      if (项.是通配 === true) return false
      return 基准流程集合.some((流程) => 项.匹配(流程))
    })

    // 规则2：若整行没有任何有意义的选项，则整行隐藏
    if (有效非通配选项们.length === 0) {
      // 隐藏时，自动将选中状态重置为通配项，避免幽灵过滤
      if (通配选项 !== undefined) {
        参数.当前选择值映射.set(维度.唯一标识, 通配选项.值)
      }
      continue
    }

    // 若有具体有效选项，则展示通配项 + 实际存在的有效非通配选项
    let 当前有效选项们: 统一维度选项[] = 通配选项 !== undefined ? [通配选项, ...有效非通配选项们] : 有效非通配选项们

    // 规则3：若当前选中值已不在有效选项中，自动回退到通配项
    let 当前选中值 = 参数.当前选择值映射.get(维度.唯一标识)
    let 选中下标 = 当前有效选项们.findIndex((项) => 项.值 === 当前选中值)
    if (选中下标 === -1) {
      选中下标 = 0
      let 首个选项 = 当前有效选项们[0]
      if (首个选项 !== undefined) {
        参数.当前选择值映射.set(维度.唯一标识, 首个选项.值)
      }
    }

    活跃维度列表.push({
      唯一标识: 维度.唯一标识,
      分类: 维度.分类,
      名称: 维度.名称,
      说明: 维度.说明,
      原始选项们: 维度.原始选项们,
      当前有效选项们,
      当前选中下标: 选中下标,
    })
  }

  // 计算最终候选流程列表
  let 候选流程列表 = 过滤流程集合()

  // 构造给渲染器的结构
  let 保留标签维度列表: 扫描维度项[] = []
  let 保留需求维度列表: 需求维度项[] = []
  let 标签选项下标们: number[] = []
  let 需求选项下标们: number[] = []

  for (let 维度 of 活跃维度列表) {
    let 选项列表: 扫描选项项[] = 维度.当前有效选项们.map((项) => ({
      值: 项.值,
      标签: 项.标签,
      说明: 项.说明,
      是通配: 项.是通配,
    }))

    if (维度.分类 === '标签') {
      保留标签维度列表.push({ 名称: 维度.名称, 说明: 维度.说明, 选项们: 选项列表 })
      标签选项下标们.push(维度.当前选中下标)
    } else {
      let 需求选项列表 = 维度.当前有效选项们.map((项) => ({ 标签: 项.标签, 说明: 项.说明 ?? '' }))
      保留需求维度列表.push({
        名称: 维度.名称,
        说明: 维度.说明 ?? '',
        选项们: 需求选项列表,
        匹配: (流程项: 流程展示项, 下标: number): boolean => {
          let 选中的选项 = 维度.当前有效选项们[下标]
          if (选中的选项 === undefined || 选中的选项.是通配 === true) return true
          return 选中的选项.匹配(流程项)
        },
      })
      需求选项下标们.push(维度.当前选中下标)
    }
  }

  return { 保留标签维度列表, 保留需求维度列表, 标签选项下标们, 需求选项下标们, 候选流程列表, 活跃维度列表 }
}
