import type { 流程, 流程标签字典, 测试模型 } from '../../src/model/requirement'
import type { 已审阅的any } from '../../src/tools/types'
import { 截断终端行, 是紧凑终端, 获得终端列数, 计算每屏方案数 } from './requirement-selector-terminal'

export type 扫描选项项 = { 值: string; 标签: string; 说明?: string | undefined; 是通配: boolean }

export type 扫描维度项 = { 名称: string; 选项们: 扫描选项项[]; 说明?: string | undefined }

export type 需求维度选项 = { 标签: string; 说明: string }

export type 需求维度项 = {
  名称: string
  说明: string
  选项们: readonly 需求维度选项[]
  匹配: (流程项: 流程展示项, 选中下标: number) => boolean
}

export type 流程展示项 = {
  流程: 流程<已审阅的any, 已审阅的any>
  流程名称: string
  标签字典: 流程标签字典
  覆盖描述: string
  所属需求名称们: readonly string[]
  依赖条件集: Set<string>
  包含人工验收: boolean
  所属模型: 测试模型<已审阅的any, 已审阅的any>
}

export type 筛选目标 =
  | { 类型: '全部'; 流程列表: 流程展示项[] }
  | { 类型: '单流程'; 流程: 流程<已审阅的any, 已审阅的any> }

export type 渲染通用选择器界面参数 = {
  标签维度列表: 扫描维度项[]
  需求维度列表: 需求维度项[]
  标签选项下标们: number[]
  需求选项下标们: number[]
  焦点下标: number
  候选流程列表: 流程展示项[]
  搜索词: string
  正在编辑搜索: boolean
}

export function 渲染通用选择器界面(参数: 渲染通用选择器界面参数): void {
  let 紧凑 = 是紧凑终端()
  let 行列表: string[] = ['🎛️  测试流程筛选', '↑↓ 移动  ←→ 切换  Enter 运行  / 搜索  Ctrl+C 取消']
  if (紧凑 === false) 行列表.push('')
  行列表.push(`🔎 搜索：${参数.搜索词}${参数.正在编辑搜索 ? '▌（输入关键词，Enter 完成）' : '（/ 输入，Esc 清空）'}`)
  if (紧凑 === false) 行列表.push('')

  // 1. 标签筛选区域
  if (参数.标签维度列表.length > 0) {
    行列表.push('按标签筛选:')
    for (let [维度索引, 维度] of 参数.标签维度列表.entries()) {
      let 当前选中 = 参数.标签选项下标们[维度索引] ?? 0
      let 选项标签列表 = 维度.选项们.map((选项, 下标) => (下标 === 当前选中 ? `[${选项.标签}]` : 选项.标签))
      let 光标 = 参数.焦点下标 === 维度索引 ? '▶' : ' '
      行列表.push(`${光标} ${维度.名称}：${选项标签列表.join('  ')}`)
    }
  }

  // 2. 需求筛选区域（换行分开）
  if (参数.需求维度列表.length > 0) {
    if (参数.标签维度列表.length > 0) 行列表.push('')
    行列表.push('按需求筛选:')
    let 标签总数 = 参数.标签维度列表.length
    for (let [需求索引, 需求维度] of 参数.需求维度列表.entries()) {
      let 当前选中 = 参数.需求选项下标们[需求索引] ?? 0
      let 选项标签列表 = 需求维度.选项们.map((选项, 下标) => (下标 === 当前选中 ? `[${选项.标签}]` : 选项.标签))
      let 绝对行索引 = 标签总数 + 需求索引
      let 光标 = 参数.焦点下标 === 绝对行索引 ? '▶' : ' '
      行列表.push(`${光标} ${需求维度.名称}：${选项标签列表.join('  ')}`)
    }
  }

  if (紧凑 === false) 行列表.push('')
  行列表.push(`当前筛选下的候选流程（共 ${参数.候选流程列表.length} 个）：`)

  // 3. 候选流程列表（首项为全部运行）
  let 筛选总行数 = 参数.标签维度列表.length + 参数.需求维度列表.length
  let 方案相对焦点 = 参数.焦点下标 - 筛选总行数
  let 全项聚焦 = 方案相对焦点 === 0
  行列表.push(`${全项聚焦 ? '▶' : ' '} [全部运行]（执行当前筛选下的所有流程）`)

  let 每屏数量 = 计算每屏方案数(筛选总行数)
  let 流程焦点 = 方案相对焦点 - 1
  let 开始下标 =
    流程焦点 < 0 ? 0 : Math.max(0, Math.min(流程焦点 - Math.floor(每屏数量 / 2), 参数.候选流程列表.length - 每屏数量))
  let 结束下标 = Math.min(参数.候选流程列表.length, 开始下标 + 每屏数量)

  for (let 索引 = 开始下标; 索引 < 结束下标; 索引 += 1) {
    let 项 = 参数.候选流程列表[索引]
    if (项 === undefined) continue
    let 是否聚焦 = 流程焦点 === 索引
    let 标签摘要 = Object.entries(项.标签字典)
      .map(([k, v]) => `${k}: ${v}`)
      .join(' | ')
    let 标签后缀 = 标签摘要 === '' ? '' : ` (${标签摘要})`
    行列表.push(`${是否聚焦 ? '▶' : ' '} ${项.流程名称}${标签后缀}`)
  }

  if (紧凑 === false) 行列表.push('')

  // 4. 底部说明（两行展示）
  let 标签总数 = 参数.标签维度列表.length
  if (参数.焦点下标 < 标签总数) {
    let 维度 = 参数.标签维度列表[参数.焦点下标]
    let 选中下标 = 参数.标签选项下标们[参数.焦点下标] ?? 0
    let 选中选项 = 维度?.选项们[选中下标]
    let 维度说明文本 = 维度?.说明 ?? `用于对测试流程进行“${维度?.名称 ?? ''}”标签分类。`
    let 选项说明文本 =
      选中选项?.说明 ??
      (选中选项?.是通配 === true
        ? `不限制“${维度?.名称 ?? ''}”，展示所有相关流程。`
        : `筛选包含“${选中选项?.标签 ?? ''}”的流程。`)
    行列表.push(`维度说明：${维度说明文本}`)
    行列表.push(`选项说明：${选项说明文本}`)
  } else if (参数.焦点下标 < 筛选总行数) {
    let 需求索引 = 参数.焦点下标 - 标签总数
    let 需求维度 = 参数.需求维度列表[需求索引]
    let 选中下标 = 参数.需求选项下标们[需求索引] ?? 0
    let 选中选项 = 需求维度?.选项们[选中下标]
    行列表.push(`需求说明：${需求维度?.说明 ?? ''}`)
    行列表.push(`选项说明：${选中选项?.说明 ?? ''}`)
  } else if (全项聚焦) {
    行列表.push(`筛选说明：已按上方标签与需求设定组合进行正交筛选。`)
    行列表.push(`操作说明：回车直接运行当前筛选出的全部 ${参数.候选流程列表.length} 个测试流程。`)
  } else {
    let 选中的流程 = 参数.候选流程列表[流程焦点]
    if (选中的流程 !== undefined) {
      行列表.push(`流程说明：${选中的流程.流程名称}`)
      行列表.push(`验收说明：${选中的流程.覆盖描述}`)
    }
  }

  let 最大宽度 = Math.max(20, 获得终端列数() - 1)
  process.stdout.write(`\u001B[2J\u001B[H${行列表.map((行) => 截断终端行(行, 最大宽度)).join('\n')}`)
}
