      await 记录浏览器画面(引擎, 提交附件, `点击账号 ${实际用户名} 所在行的「修改密码」。`, 改密按钮)
      await 引擎.点击(改密按钮)
      let 对话框 = 引擎.按角色('dialog', { name: '修改密码' })
      await 等待元素可见(对话框)
      await 引擎.输入(对话框.getByRole('textbox', { name: '新密码' }), 'Pass#2026_NewSecret!')
      let 确认按钮 = 对话框.getByRole('button', { name: '确认', exact: true })
      await 记录浏览器画面(引擎, 提交附件, '已填入新密码，点击「确认」保存。', 确认按钮)
